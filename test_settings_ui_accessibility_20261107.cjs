'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = fs.readFileSync('src/App.tsx', 'utf8');
const profile = fs.readFileSync('src/components/ProfileSettings.tsx', 'utf8');
const preferences = fs.readFileSync('src/components/ProfilePreferences.tsx', 'utf8');
const settingsStart = app.indexOf('        {/* VIEW 6: SETTINGS */}');
const settingsEnd = app.indexOf('      {createKind && (', settingsStart);
assert.ok(settingsStart >= 0 && settingsEnd > settingsStart, 'settings view boundaries are present');
const settings = app.slice(settingsStart, settingsEnd);

assert.match(app, /aria-pressed=\{appearance === value\}/);
assert.match(app, /lifeos-panel flex min-h-11 items-center justify-center/);
assert.match(app, /aria-label=\{`Preview \$\{option\.label\}`\}/);
assert.match(app, /onClick=\{cancelVisualThemePreview\}/);
assert.match(app, /onClick=\{\(\) => void applyVisualTheme\(\)\}/);
assert.match(app, /role="switch" aria-checked=\{biometricEnabled\}[^\n]*min-h-11/);
assert.match(app, /role="switch" aria-checked=\{notificationsEnabled\}[^\n]*min-h-11/);
assert.match(app, /role="switch" aria-checked=\{notificationPreferences\[key\]\}[^\n]*min-h-11/);
assert.match(app, /lifeos-input mt-1\.5 min-h-11 w-full rounded-xl px-3 py-3 text-sm/);
assert.match(preferences, /currencyOptions\.map\(code => <option key=\{code\} value=\{code\}>\{currencyLabels\.get\(code\)\}/);
assert.match(preferences, /type="search"/);
assert.match(preferences, /disabled=\{hasFinancialRecords\}/);
assert.match(preferences, /saved financial records do not yet store their own currency/);
assert.match(app, /lifeos-raised min-h-11 flex-1 rounded-xl px-3 text-xs font-semibold">Restore JSON/);
assert.match(app, /lifeos-raised min-h-11 w-full rounded-xl px-3 text-xs font-semibold">Export transactions CSV/);
assert.match(app, /developerPreviewEnabled && profileSection === 'developer'[\s\S]*?Add preview sample data/, 'sample data is available only inside the gated Preview developer section');
const dataStart = settings.indexOf("profileSection === 'data'");
const dataEnd = settings.indexOf("profileSection === 'about'", dataStart);
assert.ok(dataStart >= 0 && dataEnd > dataStart, 'data and about section boundaries are present');
assert.doesNotMatch(settings.slice(dataStart, dataEnd), /seedDemoData\(\)/, 'sample data is kept away from backup and ordinary settings');
assert.match(app, /lifeos-raised min-h-11 w-full rounded-xl px-3 text-xs font-semibold disabled:opacity-50">Add preview sample data/);
assert.match(settings, /lifeos-panel rounded-2xl border p-5 space-y-4/);
assert.match(profile, /profile-avatar lifeos-accent-button flex h-16 w-16/);
assert.match(profile, /aria-label="Profile settings"/);
assert.match(profile, /developerAllowed && <ProfileNavigationRow title="Developer \/ Preview"/);
assert.match(profile, /data-testid="profile-settings-subpage"/);
assert.ok(!/\b(?:text|bg|border)-(?:slate|indigo|emerald|amber|rose)-\d{2,3}\b/.test(settings), 'settings colors use semantic theme tokens');
assert.match(settings, /lifeos-danger min-h-11 w-full rounded-xl border/);

console.log('SETTINGS UI: theme, preference, switch, profile navigation and export accessibility checks passed.');
