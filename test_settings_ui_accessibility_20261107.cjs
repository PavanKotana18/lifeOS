'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = fs.readFileSync('src/App.tsx', 'utf8');
const profile = fs.readFileSync('src/components/ProfileSettings.tsx', 'utf8');
const preferences = fs.readFileSync('src/components/ProfilePreferences.tsx', 'utf8');
const settingsStart = app.indexOf('        {/* VIEW 6: SETTINGS */}');
const settingsEnd = app.indexOf('      {createKind && (', settingsStart);
assert.ok(settingsStart >= 0 && settingsEnd > settingsStart, 'settings view boundaries are present');
const settings = app.slice(settingsStart, settingsEnd);

const component = name => fs.readFileSync('src/components/' + name + '.tsx', 'utf8');
const studio = component('AppearanceStudio');
const styles = fs.readFileSync('src/styles/premium-profile.css', 'utf8');
assert.match(studio, /aria-pressed=\{appearance === mode\}/);
assert.match(studio, /aria-label=\{'Preview ' \+ option\.label\}/);
assert.match(studio, /aria-pressed=\{shown === id\}/);
assert.match(studio, /onClick=\{onCancel\}/);
assert.match(studio, /onClick=\{onApply\}/);
assert.match(styles, /--profile-target: max\(48px, 3rem\)/);
assert.match(styles, /min-block-size: var\(--profile-target\)/);
assert.match(component('ProfileWorkspace'), /<ProfileToggle title="App lock" checked=\{enabled\}/);
assert.match(component('ProfileNotifications'), /<ProfileToggle title="Android reminders"[\s\S]*?checked=\{master\}/);
assert.match(component('ProfileNotifications'), /checked=\{Boolean\(categories\[key\]\)\}/);
assert.match(profile, /role="switch" aria-label=\{title\} aria-checked=\{checked\}/);
assert.match(preferences, /currencyOptions = useMemo\(\(\) => CURRENCY_CODES\.map/);
assert.match(component('PreferenceChoice'), /type="search"/);
assert.match(preferences, /disabled=\{hasFinancialRecords \|\| saving\}/);
assert.match(preferences, /Locked while financial records exist/);
assert.doesNotMatch(component('PreferenceChoice'), /Currency is locked/);
const data = component('ProfileData');
assert.match(data, /Choose backup file/);
assert.match(data, /Export transactions CSV/);
assert.match(data, /tone="danger" disabled=\{busy\} onClick=\{onReset\}/);
assert.match(settings, /developerToolsEnabled && profileSection === 'developer'[\s\S]*?<ProfileDeveloper/);
assert.match(component('ProfileDeveloper'), /Add sample data/);
assert.doesNotMatch(data, /seedDemoData/);
assert.match(profile, /profile-avatar-picture/);
assert.match(styles, /\.profile-avatar-picture \{[\s\S]*?border-radius: 50%/);
assert.match(profile, /aria-label="Profile settings"/);
assert.match(profile, /developerAllowed &&[\s\S]*?title="Developer tools"/);
assert.match(profile, /data-testid="profile-settings-subpage"/);
assert.ok(!/\b(?:text|bg|border)-(?:slate|indigo|emerald|amber|rose)-\d{2,3}\b/.test(settings), 'settings colors use semantic theme tokens');

console.log('SETTINGS UI: palette controls, touch targets, preference access, developer gating and protected data controls passed.');
