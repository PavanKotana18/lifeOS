"use strict";
const assert = require('node:assert/strict');
require('./scripts/register-ts-test-loader.cjs');
const { EditorState, TextSelection } = require('prosemirror-state');
const { history, undo } = require('prosemirror-history');
const { notesSchema, noteDocument, parseNoteDocument } = require('./src/services/notesDocument.ts');
const { formatNoteList, splitChecklist } = require('./src/services/noteFormatting.ts');
const n = notesSchema.nodes;
const p = (text, strong = false) => n.paragraph.create(null, notesSchema.text(text, strong ? [notesSchema.marks.strong.create()] : []));
const item = (...blocks) => n.list_item.create(null, blocks);
const doc = (...blocks) => n.doc.create(null, blocks);
function stateAt(document, text, offset = 0) {
  let found;
  document.descendants((node, pos) => { if (node.isTextblock && node.textContent === text) found = pos + 1 + offset; });
  assert.notEqual(found, undefined);
  return EditorState.create({ doc: document, selection: TextSelection.create(document, found), plugins: [history()] });
}
function apply(state, command) {
  let result;
  assert.equal(command(state, tr => { result = state.apply(tr); }), true);
  assert.ok(result);
  parseNoteDocument(noteDocument(result.doc));
  return result;
}
let s = stateAt(doc(p('Before'), n.bullet_list.create(null, [item(p('First', true)), item(p('Second'))]), p('After')), 'Second', 3);
s = apply(s, formatNoteList(n.ordered_list));
assert.equal(s.doc.child(1).type, n.ordered_list);
assert.equal(s.selection.$from.parentOffset, 3);
s = apply(s, formatNoteList(n.checklist_item));
assert.deepEqual([s.doc.child(0).textContent, s.doc.child(1).textContent, s.doc.child(2).textContent, s.doc.child(3).textContent], ['Before', 'First', 'Second', 'After']);
assert.equal(s.doc.child(1).firstChild.marks[0].type, notesSchema.marks.strong);
assert.notEqual(s.doc.child(1).attrs.id, s.doc.child(2).attrs.id);
assert.equal(s.selection.$from.parentOffset, 3);
s = apply(s, formatNoteList(n.bullet_list));
assert.equal(s.doc.child(1).type, n.bullet_list);
assert.equal(s.doc.child(1).childCount, 2);
s = apply(s, undo);
assert.equal(s.doc.child(1).type, n.checklist_item);
const checked = n.checklist_item.create({ id: 'existing-check', checked: true }, notesSchema.text('Entry'));
s = stateAt(doc(checked), 'Entry', 5);
s = apply(s, splitChecklist);
assert.equal(s.doc.childCount, 2);
assert.equal(s.doc.child(0).attrs.id, 'existing-check');
assert.equal(s.doc.child(1).type, n.checklist_item);
assert.equal(s.doc.child(1).attrs.checked, false);
assert.notEqual(s.doc.child(1).attrs.id, 'existing-check');
assert.equal(s.selection.$from.parent.type, n.checklist_item);
assert.equal(s.selection.$from.parentOffset, 0);
s = apply(s, splitChecklist);
assert.equal(s.doc.child(1).type, n.paragraph);
const selected = doc(p('Alpha'), p('Beta'), p('Untouched'));
let selectionState = EditorState.create({ doc: selected, selection: TextSelection.create(selected, 1, selected.child(0).nodeSize + 1 + 4) });
selectionState = apply(selectionState, formatNoteList(n.checklist_item));
assert.equal(selectionState.doc.child(0).type, n.checklist_item);
assert.equal(selectionState.doc.child(1).type, n.checklist_item);
assert.equal(selectionState.doc.child(2).type, n.paragraph);
selectionState = apply(selectionState, formatNoteList(n.ordered_list));
assert.equal(selectionState.doc.child(0).type, n.ordered_list);
assert.equal(selectionState.doc.child(0).childCount, 2);
assert.equal(selectionState.doc.child(1).textContent, 'Untouched');
selectionState = apply(selectionState, formatNoteList(n.bullet_list));
assert.equal(selectionState.doc.child(0).type, n.bullet_list);
const nested = doc(n.bullet_list.create(null, [item(p('Parent'), n.bullet_list.create(null, [item(p('Child'))]))]));
let nestedState = stateAt(nested, 'Child', 2);
nestedState = apply(nestedState, formatNoteList(n.ordered_list));
assert.equal(nestedState.doc.child(0).child(0).child(1).type, n.bullet_list);
nestedState = apply(nestedState, formatNoteList(n.checklist_item));
assert.deepEqual([nestedState.doc.child(0).textContent, nestedState.doc.child(1).textContent], ['Parent', 'Child']);
console.log('Notes formatting: conversion, marks, selection, undo and checklist Enter passed.');
