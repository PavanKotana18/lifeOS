'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = fs.readFileSync('src/App.tsx', 'utf8');
const start = app.indexOf('        {/* VIEW 5: PLANNER */}');
const end = app.indexOf('        {/* VIEW 6: SETTINGS */}', start);
assert.ok(start >= 0 && end > start, 'Planner view boundaries are present');
const planner = app.slice(start, end);
const taskDetail = fs.readFileSync('src/components/TaskDetailScreen.tsx', 'utf8');
const plannerAndDetail = `${planner}\n${taskDetail}`;
assert.ok(!/\b(?:text|bg|border)-(?:slate|indigo|emerald|amber|rose|sky|violet)-\d{2,3}(?:\/\d+)?\b/.test(planner), 'Planner uses semantic palette tokens');
assert.match(planner, /lifeos-panel/);
assert.match(planner, /lifeos-input/);
assert.match(planner, /lifeos-accent-button/);
assert.match(planner, /hover:bg-\[var\(--surface-raised\)\]/);
assert.match(planner, /aria-pressed=\{selected\}/);
assert.match(planner, /min-h-11 min-w-11/);
assert.match(plannerAndDetail, /text-\[var\(--danger\)\]/);
assert.match(plannerAndDetail, /text-\[var\(--success\)\]/);
assert.match(taskDetail, /role="dialog" aria-modal=\{present \|\| undefined\} aria-hidden=\{!present \|\| undefined\}[\s\S]*aria-labelledby="task-detail-title"/);
assert.match(planner, /<details className="planner-filters">[\s\S]*aria-label="Search planner tasks"[\s\S]*aria-label="Task date or status filter"[\s\S]*aria-label="Task priority filter/);
assert.match(app, /plannerFilter === 'upcoming' \? Boolean\(task\.dueDate\) && task\.dueDate > todayKey[\s\S]{0,120}\+ 7/);
assert.doesNotMatch(fs.readFileSync('src/components/PlanHub.tsx', 'utf8'), /aria-label="Open calendar"/, 'calendar is absent from the Plan toolbar');
assert.match(fs.readFileSync('src/components/PlanHub.tsx', 'utf8'), /aria-pressed=\{view === item.id\} onClick=\{\(\) => setView\(item.id\)\}/, 'Plan date tabs filter the visible tasks in place');
console.log('PLANNER THEME: 14 source-level palette, date selection, progressive-filter and status checks passed.');
