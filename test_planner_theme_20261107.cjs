'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = fs.readFileSync('src/App.tsx', 'utf8');
const start = app.indexOf('        {/* VIEW 5: PLANNER */}');
const end = app.indexOf('        {/* VIEW 6: SETTINGS */}', start);
assert.ok(start >= 0 && end > start, 'Planner view boundaries are present');
const planner = app.slice(start, end);
assert.ok(!/\b(?:text|bg|border)-(?:slate|indigo|emerald|amber|rose|sky|violet)-\d{2,3}(?:\/\d+)?\b/.test(planner), 'Planner uses semantic palette tokens');
assert.match(planner, /lifeos-panel/);
assert.match(planner, /lifeos-input/);
assert.match(planner, /lifeos-accent-button/);
assert.match(planner, /hover:bg-\[var\(--surface-raised\)\]/);
assert.match(planner, /aria-pressed=\{selected\}/);
assert.match(planner, /min-h-11 min-w-11/);
assert.match(planner, /text-\[var\(--danger\)\]/);
assert.match(planner, /text-\[var\(--success\)\]/);
assert.match(planner, /aria-label="Task details"/);
console.log('PLANNER THEME: 11 source-level palette, date selection and status checks passed.');
